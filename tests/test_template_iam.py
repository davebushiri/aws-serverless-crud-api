"""Least-privilege checks on the fully expanded SAM template (offline, no AWS calls).

The SAM transform runs locally with a stubbed managed-policy lookup, so these
tests see exactly what CloudFormation would receive, including anything SAM adds.
"""

import pathlib

import pytest
from samtranslator.translator.transform import transform
from samtranslator.yaml_helper import yaml_parse

TEMPLATE = pathlib.Path(__file__).resolve().parents[1] / "template.yaml"


class _OfflinePolicyLoader:
    """Stands in for the default loader, which would call the IAM ListPolicies API."""

    def load(self):
        return {"AWSLambdaBasicExecutionRole": "arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole"}


@pytest.fixture(scope="module")
def expanded():
    template = yaml_parse(TEMPLATE.read_text())
    template["Resources"]["ItemsFunction"]["Properties"]["CodeUri"] = "s3://placeholder/code.zip"
    return transform(template, {}, _OfflinePolicyLoader())["Resources"]


def test_single_explicit_role_without_managed_policies(expanded):
    roles = {name: r for name, r in expanded.items() if r["Type"] == "AWS::IAM::Role"}
    assert list(roles) == ["ItemsFunctionExecutionRole"]  # declared in template.yaml, not generated by SAM
    assert "ManagedPolicyArns" not in roles["ItemsFunctionExecutionRole"]["Properties"]
    assert expanded["ItemsFunction"]["Properties"]["Role"] == {"Fn::GetAtt": ["ItemsFunctionExecutionRole", "Arn"]}


def test_role_grants_only_scoped_actions(expanded):
    role = expanded["ItemsFunctionExecutionRole"]["Properties"]
    trust = role["AssumeRolePolicyDocument"]["Statement"]
    assert trust == [{"Effect": "Allow", "Principal": {"Service": "lambda.amazonaws.com"}, "Action": "sts:AssumeRole"}]

    statements = [s for policy in role["Policies"] for s in policy["PolicyDocument"]["Statement"]]
    assert all(s["Effect"] == "Allow" and s["Resource"] != "*" for s in statements)
    granted = {(action, str(s["Resource"])) for s in statements for action in s["Action"]}
    table = str({"Fn::GetAtt": ["ItemsTable", "Arn"]})
    log_streams = str({"Fn::Sub": "arn:${AWS::Partition}:logs:${AWS::Region}:${AWS::AccountId}:"
                                  "log-group:${ItemsFunctionLogGroup}:log-stream:*"})
    assert granted == {
        ("dynamodb:GetItem", table), ("dynamodb:PutItem", table),
        ("dynamodb:DeleteItem", table), ("dynamodb:Scan", table),
        ("logs:CreateLogStream", log_streams), ("logs:PutLogEvents", log_streams),
    }
